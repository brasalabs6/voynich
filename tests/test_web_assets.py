"""Static integrity checks for the archival reader and source index."""
from html.parser import HTMLParser
import json
from pathlib import Path
import unittest

ROOT = Path(__file__).resolve().parents[1]

class GetIds(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids=[]
    def handle_starttag(self,tag,attrs):
        values=dict(attrs)
        if "id" in values:
            self.ids.append(values["id"])

class WebTests(unittest.TestCase):
    def test_html_anchors_are_unique_and_referenced(self):
        html=(ROOT/"web/index.html").read_text(encoding="utf-8")
        script=(ROOT/"web/app.js").read_text(encoding="utf-8")
        p=GetIds()
        p.feed(html)
        self.assertEqual(len(p.ids),len(set(p.ids)))
        for name in ("viewer","folioList","previousPage","nextPage",
                     "folioSearch","transcriptionLines","ivtffUpload",
                     "noteText","exportNotes","zoomIn","zoomOut",
                     "resetZoom","sourceInfoButton","toast"):
            self.assertIn(name,p.ids)
            self.assertIn(name,script)

    def test_yale_index_has_provenance_and_folio_1(self):
        path=ROOT/"web/data/folios.json"
        if not path.exists():
            self.skipTest("Index generated by an online Github Action")
        obj=json.loads(path.read_text(encoding="utf-8"))
        self.assertGreaterEqual(obj["canvas_count"],200)
        self.assertEqual(len(obj["pages"]),obj["canvas_count"])
        self.assertGreaterEqual(obj["zoomable_count"],190)
        self.assertEqual(len(obj["source_sha256"]),64)
        self.assertIn("collections.library.yale.edu",obj["source"])
        self.assertTrue(any(p["folio"]=="f1r" for p in obj["pages"]))
        for i,p in enumerate(obj["pages"],1):
            self.assertEqual(p["seq"],i)
            self.assertTrue(p["image_info"] or p["image_fallback"])

if __name__=="__main__":
    unittest.main()

